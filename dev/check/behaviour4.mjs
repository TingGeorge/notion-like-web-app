// --- Paste & drop & upload ---------------------------------------------------------------------
{
  const { browser, page, errors } = await launch({ empty: true })
  await page.click('.gn-prose p')
  const paste = (data) =>
    page.evaluate((d) => {
      const dt = new DataTransfer()
      if (d.text) dt.setData('text/plain', d.text)
      if (d.html) dt.setData('text/html', d.html)
      for (const f of d.files ?? []) dt.items.add(new File([f.content], f.name, { type: f.type }))
      const ev = new ClipboardEvent('paste', { clipboardData: dt, bubbles: true, cancelable: true })
      window.__gn.handle.view.dom.dispatchEvent(ev)
    }, data)
  await paste({ text: 'line one\nline two' })
  let doc = await top(page)
  check('plain text pastes as paragraphs', doc.length >= 2 && txt(doc[0]).startsWith('line one') && txt(doc[1]).startsWith('line two'), JSON.stringify(doc.map(txt)))
  await page.keyboard.press('Control+a')
  await page.keyboard.press('Backspace')
  await paste({ text: '# 標題\n\n- 一\n- 二' })
  doc = await top(page)
  check('Markdown paste falls back to paragraphs while parseMarkdown is a stub', doc.length >= 3, JSON.stringify(doc.map((n) => n.type + txt(n))))
  await page.keyboard.press('Control+a')
  await page.keyboard.press('Backspace')
  await paste({ html: '<h2>Hello</h2><p>x <strong>bold</strong><script>alert(1)</script><img src="javascript:alert(1)"><a href="javascript:alert(2)">bad</a></p><ul><li>one</li><li>two</li></ul>', text: 'Hello x bold' })
  doc = await top(page)
  const json = JSON.stringify(doc)
  check('HTML paste: sanitised and converted', doc[0].type === 'heading' && !json.includes('alert') && !json.includes('javascript'), JSON.stringify(doc.map((n) => n.type)))
  check('HTML paste keeps bold and lists', json.includes('"bold"') && doc.some((n) => n.type === 'bullet_list'))
  await page.keyboard.press('Control+a')
  await page.keyboard.press('Backspace')
  // image paste -> upload placeholder -> image block
  await paste({ files: [{ name: 'pic.png', type: 'image/png', content: 'x' }] })
  await page.waitForSelector('.upload-placeholder')
  await page.screenshot({ path: `${OUT}/upload.png`, clip: { x: 300, y: 0, width: 800, height: 200 } })
  check('upload placeholder shows while uploading', (await page.locator('.upload-placeholder').count()) === 1)
  await page.waitForSelector('.image-block', { timeout: 5000 })
  doc = await top(page)
  check('uploaded image becomes an image block replacing the empty paragraph', doc[0].type === 'image' && doc[0].attrs.src === '/_assets/2026/10/pic.png', JSON.stringify(doc.map((n) => n.type)))
  check('placeholder is gone', (await page.locator('.upload-placeholder').count()) === 0)
  await paste({ files: [{ name: 'doc.pdf', type: 'application/pdf', content: 'x' }] })
  await page.waitForSelector('.file-block', { timeout: 5000 })
  doc = await top(page)
  check('other files become file blocks', doc.some((n) => n.type === 'file' && n.attrs.name === 'doc.pdf'))
  check('doc ends with a paragraph after atoms', doc.at(-1).type === 'paragraph', doc.at(-1).type)
  // oversized
  await paste({ files: [{ name: 'huge.bin', type: 'application/octet-stream', content: new Array(1).fill('x').join('') }] })
  // callout pasted inside a list becomes a quote
  const r = await page.evaluate(() => {
    const view = window.__gn.handle.view
    const s = view.state.schema
    const callout = s.nodes.callout.create({ kind: 'NOTE' }, s.nodes.paragraph.create(null, s.text('c')))
    const list = s.nodes.bullet_list.create(null, s.nodes.list_item.create({ checked: null }, s.nodes.paragraph.create(null, s.text('item'))))
    const doc = s.nodes.doc.create(null, [list])
    const state = view.state.constructor.create({ doc, plugins: view.state.plugins })
    return !!state
  })
  void r
  console.log('errors', errors)
  await browser.close()
}

